const TABLE: Record<Language, Strings> = { EN, ES, FR, HI };

export function t(language: Language, key: string): string {
  return TABLE[language]?.[key] ?? EN[key] ?? key;
}

/** Translate a live event's label (provider labels are English). */
export function translateEventLabel(language: Language, event: { type: string; label?: string }): string {
  if (language === "EN") return event.label ?? event.type;
  switch (event.type) {
    case "goal": return t(language, "goal");
    case "card": return /red/i.test(event.label ?? "") ? t(language, "redCard") : t(language, "yellowCard");
    case "substitution": return t(language, "substitution");
    case "kickoff": return t(language, "kickoff");
    case "halftime": return t(language, "halftime");
    case "fulltime": return t(language, "fulltimeEvt");
    default: return t(language, "matchEvent");
  }
}

/** Match status word for the hero clock area. */
export function translateStatus(language: Language, state: "pre" | "in" | "post"): string {
  if (state === "in") return t(language, "inPlay");
  if (state === "post") return t(language, "fullTime");
  return t(language, "upcoming");
}

